import { expect, it } from 'vitest'
it('add expense -> totals/balances/settlement update; pay -> settled; delete + undo', async () => {
  localStorage.setItem('roomly.token', 'mock.m_rahul')
  const { expenseService } = await import('@/services/expenseService')
  const { settlementService } = await import('@/services/settlementService')
  const before = await settlementService.getSettlement('2026-10')
  expect(before.total).toBe(18420); expect(before.fairShare).toBe(4605); expect(before.status).toBe('open')
  expect(before.members.reduce((s, m) => s + m.balance, 0)).toBe(0)
  const e = await expenseService.createExpense({ title: 'Vegetables', amount: 450, category: 'vegetables', paidBy: 'm_vikas', date: '2026-10-28' })
  const after = await settlementService.getSettlement('2026-10')
  expect(after.total).toBe(18870); expect(after.members.reduce((s, m) => s + m.balance, 0)).toBe(0)
  console.log('after add:', after.members.map((m) => m.balance), after.transactions.map((t) => `${t.from}>${t.to}:${t.amount}`))
  const found = await expenseService.getExpenses({ month: '2026-10', q: 'grocery' })
  expect(found.length).toBeGreaterThan(5)
  const del = await expenseService.deleteExpense(e.id)
  await expenseService.restoreExpense(del)
  expect((await settlementService.getSettlement('2026-10')).total).toBe(18870)
  await expenseService.deleteExpense(e.id)
  let s = await settlementService.getSettlement('2026-10')
  for (const t of s.transactions) s = await settlementService.markSettlementPaid('2026-10', t.id)
  expect(s.status).toBe('settled')
  await expect(expenseService.getExpense('nope')).rejects.toMatchObject({ status: 404 })
  await expect(expenseService.createExpense({ title: '', amount: 0, category: 'other', paidBy: 'm_rahul', date: '2026-10-28' })).rejects.toMatchObject({ status: 422 })
})
